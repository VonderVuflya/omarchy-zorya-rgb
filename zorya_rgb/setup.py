def install_plugin(*,dry_run=False,data_home=None,run=subprocess.run):
    data,_,_=_paths(data_home)
    plan=[_action('Install plugin, Python environment and Zorya user daemon',
                  [sys.executable,ROOT/'scripts/install-plugin.py','--data-home',data],600)]
    if dry_run:return dict(ok=True,plan=plan,actions=[],error=None,preserves_state=True)
    return _run_plan(plan,run)


def uninstall_plugin(*,dry_run=False,data_home=None,run=subprocess.run):
    data,_,units=_paths(data_home)
    meta=_metadata(data)
    managed=[u for u in meta.get('hardware_units',[]) if u in UNITS]
    managed.append('zorya-rgb.service')
    plan=[_action('Stop only Zorya-owned services',['systemctl','--user','disable','--now',*managed]),
          _action('Reload user units',['systemctl','--user','daemon-reload'])]
    if dry_run:return dict(ok=True,plan=plan,actions=[],error=None,preserves_state=True)
    report=_run_plan(plan[:1],run)
    if not report['ok']:return report
    for unit in managed:
        (units/unit).unlink(missing_ok=True)
    plugin=meta.get('plugin')
    identity=meta.get('plugin_id','vondervuflya.zorya-rgb')
    expected=Path(os.environ.get('XDG_CONFIG_HOME',Path.home()/'.config'))/'omarchy/plugins'/identity
    if plugin and Path(plugin)==expected and (expected/'manifest.json').exists():
        if shutil.which('omarchy'):
            removed=_run_plan([_action('Remove native bar widget and back up its plugin',['omarchy','plugin','remove',identity,'--yes'])],run)
            if not removed['ok']:return dict(removed,preserves_state=True)
        else:
            return dict(ok=False,error='Omarchy CLI unavailable; plugin retained to avoid leaving a broken bar entry',preserves_state=True)
    binpath=Path.home()/'.local/bin/zorya-rgb'
    if binpath.is_symlink() and 'omarchy-zorya-rgb' in str(binpath.resolve()):
        binpath.unlink()
    # Restore service selection only when setup recorded its former enablement.
    for prior in meta.get('adopted',[]):
        unit=prior.get('unit','')
        if not unit.endswith('.service') or unit.startswith('zorya-') or '/' in unit:continue
        restore=[]
        if prior.get('enabled'):restore.append(_action('Restore previous service enablement',['systemctl','--user','enable',unit]))
        if prior.get('active'):restore.append(_action('Restore previously active service',['systemctl','--user','start',unit]))
        if restore:
            restored=_run_plan(restore,run)
            if not restored['ok']:return dict(restored,preserves_state=True)
    report=_run_plan(plan[1:],run)
    if report['ok']:
        meta['hardware_units']=[]
        meta['endpoints']={}
        meta['uninstalled']=True
        if data.exists():
            (data/'installation.json').write_text(json.dumps(meta,indent=2))
            (data/'installation.json').chmod(0o600)
    report['preserves_state']=True
    return report


def migrate(*,source=None,destination=None,dry_run=False,backend=None):
    config=Path(os.environ.get('XDG_CONFIG_HOME',Path.home()/'.config'))
    candidates=[config/'omarchy/plugins/didlix.case-rgb/state.json',config/'omarchy-rgb/state.json',
                Path(os.environ.get('XDG_STATE_HOME',Path.home()/'.local/state'))/'omarchy-rgb/state.json']
    src=Path(source) if source else next((p for p in candidates if p.is_file()),None)
    dst=Path(destination) if destination else Path(os.environ.get('XDG_STATE_HOME',Path.home()/'.local/state'))/'zorya-rgb/state.json'
    if src is None:return dict(ok=False,error='No legacy state found; supply an explicit source path')
    try:
        old=json.loads(src.read_text())
        if not isinstance(old,dict):raise ValueError('Legacy state must be a JSON object')
        allowed=('color','brightness','effect','speed','secondary_color')
        state={k:v for k,v in old.items() if k in allowed}
        state['on']=old.get('on',old.get('enabled',True))
        pending=list(old.get('devices') or ([old['device']] if old.get('device') else []))
        available=[]
        owned=backend is None
        if owned:
            from .openrgb_backend import OpenRGBBackend
            backend=OpenRGBBackend()
        try:
            backend.connect()
            available=backend.devices([])
        finally:
            if owned:backend.close()
        selected=[]; ambiguous=[]; unmatched=[]
        for name in pending:
            matches=[d['id'] for d in available if d['name'].casefold()==str(name).casefold() or d['id']==name]
            if len(matches)==1:selected.extend(matches)
            elif len(matches)>1:ambiguous.append(name)
            else:unmatched.append(name)
        if not pending and not old.get('devices_none',False):selected=[d['id'] for d in available]
        state['devices']=[] if old.get('devices_none') else list(dict.fromkeys(selected))
        from .state import DEFAULT_STATE,validate_patch
        state=validate_patch(DEFAULT_STATE,state)
        if dst.exists():raise ValueError('Destination already exists; migration will not overwrite it')
        if not dry_run:
            dst.parent.mkdir(parents=True,exist_ok=True)
            fd=os.open(dst,os.O_WRONLY|os.O_CREAT|os.O_EXCL,0o600)
            with os.fdopen(fd,'w') as stream:json.dump(state,stream,indent=2)
        return dict(ok=True,error=None,source=str(src),destination=str(dst),state=state,preserves_original=True,pending_names=unmatched,ambiguous_names=ambiguous)
    except (OSError,ValueError) as error:
        return dict(ok=False,error=str(error),preserves_original=True)


def pair_device(device_id,*,ipc=None,timeout=10):
    """Bind only a currently enumerated unbound device, through private user IPC."""
    import re
    match=re.fullmatch(r'wireless-unbound:((?:[0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2})',device_id) if isinstance(device_id,str) else None
    if not match:return dict(ok=False,error='Pairing requires a current wireless-unbound ID with a six-byte MAC')
    mac=match[1].lower();unbound='wireless-unbound:'+mac;bound='wireless:'+mac
    ipc=ipc or hardware._lianli_ipc
    try:
        devices=hardware.wireless_devices(ipc)
        if any(d['device_id'].lower()==bound and not d['is_unbound_wireless'] for d in devices):
            return dict(ok=True,already_paired=True,device_id=bound,error=None)
        if not any(d['device_id'].lower()==unbound and d['is_unbound_wireless'] for d in devices):
            raise ValueError('Device is not currently listed as unbound; refresh hardware diagnostics')
        ipc('BindWirelessDevice',{'mac':mac})
        deadline=time.monotonic()+timeout
        while True:
            current=hardware.wireless_devices(ipc)
            if any(d['device_id'].lower()==bound and not d['is_unbound_wireless'] for d in current):
                return dict(ok=True,already_paired=False,device_id=bound,error=None)
            if time.monotonic()>=deadline:
                raise TimeoutError('Pairing command queued but bound-device discovery timed out; refresh diagnostics before retrying')
            time.sleep(.25)
    except (OSError,ValueError,RuntimeError,TimeoutError) as error:
        return dict(ok=False,error=str(error),device_id=unbound)
